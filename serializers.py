"""Serializers for the stapel-analytics API.

Model-backed response serializers are generated by the presenters
(``stapel_core.django.api.presenters.Presenter``); request serializers and
non-model envelopes live here.

The ingest REQUEST serializer is deliberately loose — ``events`` is a list
of free-form objects and nothing more. Per-event validation happens in
``ingest.normalize_batch``, because DRF's answer to a bad item in a list is
to refuse the whole list, and this endpoint's contract is the opposite:
accept what is valid, name what is not, and never make a retrying offline
buffer choose between twenty events and one.
"""
from __future__ import annotations

from rest_framework import serializers
from stapel_core.django.api.serializers import StapelDataclassSerializer

from .dto import (
    EventRegistry,
    EventsReport,
    FunnelDefinition,
    FunnelReportDTO,
    FunnelStep,
    IngestReceipt,
)
from .presenters import get_funnel_presenter

FunnelSerializer = get_funnel_presenter().serializer_class()


# ── Envelope responses ───────────────────────────────────────────────


class IngestReceiptSerializer(StapelDataclassSerializer):
    class Meta:
        dataclass = IngestReceipt


class EventRegistrySerializer(StapelDataclassSerializer):
    class Meta:
        dataclass = EventRegistry


class FunnelDefinitionSerializer(StapelDataclassSerializer):
    class Meta:
        dataclass = FunnelDefinition


class FunnelStepSerializer(StapelDataclassSerializer):
    """One step of a computed report.

    The two rates are RATIOS in [0, 1] (step counts never grow along a
    funnel), declared with their bounds so no reader takes them for money or
    for a percentage.
    """

    rate_from_first = serializers.FloatField(
        min_value=0, max_value=1,
        help_text="Ratio in [0, 1]: this step's count over the first step's.",
    )
    rate_from_previous = serializers.FloatField(
        min_value=0, max_value=1,
        help_text="Ratio in [0, 1]: this step's count over the previous step's (1 on the first step when it has subjects).",
    )

    class Meta:
        dataclass = FunnelStep


class FunnelReportSerializer(StapelDataclassSerializer):
    steps = FunnelStepSerializer(many=True)

    class Meta:
        dataclass = FunnelReportDTO


class EventsReportSerializer(StapelDataclassSerializer):
    class Meta:
        dataclass = EventsReport


# ── Requests ─────────────────────────────────────────────────────────


class IngestEventSerializer(serializers.Serializer):
    """One event of a batch, in the facade's spelling.

    The collector also reads the snake_case spellings (``user_hash``,
    ``event_id``) and ``timestamp``/``traits`` aliases; this is the shape a
    generated client sends. Faults are reported per event in the receipt,
    never by refusing the batch.
    """

    id = serializers.CharField(
        required=False, help_text="Client event id, echoed into the store as event_id."
    )
    kind = serializers.ChoiceField(choices=["track", "page", "identify"], default="track")
    name = serializers.CharField(
        required=False, help_text="Event name; a registered one for kind=track."
    )
    props = serializers.DictField(required=False, help_text="Event properties (PII-guarded).")
    userHash = serializers.CharField(  # noqa: N815 — the facade's wire spelling
        required=False, help_text="sha256 hex of the account id, after identify()."
    )
    ts = serializers.IntegerField(
        required=False, help_text="Epoch milliseconds; server time when absent."
    )
    anon_id = serializers.CharField(required=False, help_text="Overrides the batch anon_id.")
    session_id = serializers.CharField(required=False, help_text="Overrides the batch session_id.")
    source = serializers.CharField(required=False, help_text="Overrides the batch source.")


class IngestContextSerializer(serializers.Serializer):
    """The emitter of a batch, copied onto every stored event."""

    platform = serializers.CharField(required=False, help_text="ios, android, desktop, web")
    app_version = serializers.CharField(required=False)
    os_version = serializers.CharField(required=False)
    locale = serializers.CharField(required=False, help_text="BCP 47 tag, e.g. en-US")
    sdk = serializers.CharField(required=False, help_text="Collector name and version")


class IngestSerializer(serializers.Serializer):
    """The batch, as ``@stapel/analytics`` and the native collector send it.

    ``write_key`` is optional because the shipped facade omits it unless a
    host configured one; ``anon_id`` / ``session_id`` are batch-level
    defaults the current facade does not send at all and a server-side
    producer does; ``context`` describes the emitter. See ``ingest.py`` for
    the whole wire contract.
    """

    events = IngestEventSerializer(many=True, allow_empty=True)
    write_key = serializers.CharField(required=False, allow_blank=True)
    anon_id = serializers.CharField(required=False, allow_blank=True)
    session_id = serializers.CharField(required=False, allow_blank=True)
    context = IngestContextSerializer(required=False)


class FunnelCreateSerializer(serializers.Serializer):
    slug = serializers.SlugField(max_length=100)
    steps = serializers.ListField(child=serializers.CharField(max_length=200))
    title = serializers.CharField(max_length=200, required=False, allow_blank=True)
    description = serializers.CharField(required=False, allow_blank=True)
    window_seconds = serializers.IntegerField(required=False, min_value=1)
    is_active = serializers.BooleanField(required=False, default=True)
    workspace_id = serializers.UUIDField(required=False, allow_null=True)


class FunnelPatchSerializer(serializers.Serializer):
    steps = serializers.ListField(child=serializers.CharField(max_length=200),
                                  required=False)
    title = serializers.CharField(max_length=200, required=False, allow_blank=True)
    description = serializers.CharField(required=False, allow_blank=True)
    window_seconds = serializers.IntegerField(required=False, min_value=1)
    is_active = serializers.BooleanField(required=False)


class ReportQuerySerializer(serializers.Serializer):
    start = serializers.DateTimeField(required=False)
    end = serializers.DateTimeField(required=False)
    compare = serializers.BooleanField(required=False, default=False)


class EventsReportQuerySerializer(serializers.Serializer):
    start = serializers.DateTimeField(required=False)
    end = serializers.DateTimeField(required=False)
    #: Payload keys to group by. ``name`` is the useful default (what was
    #: fired, how often); ``source`` and ``kind`` are the other two a
    #: dashboard asks for.
    group_by = serializers.ListField(
        child=serializers.ChoiceField(choices=["name", "source", "kind"]),
        required=False,
    )


class FunnelListQuerySerializer(serializers.Serializer):
    workspace_id = serializers.UUIDField(required=False, allow_null=True)
    mine = serializers.BooleanField(required=False, default=False)
    #: Bounded by STAPEL_ANALYTICS["MAX_PAGE_SIZE"] — a caller may ask for
    #: less, never for more.
    limit = serializers.IntegerField(required=False, min_value=1)


